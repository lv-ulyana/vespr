int reduce22(int n) {
  var x = n;
  while (x > 22) {
    x -= 22;
  }
  return x;
}

int arcanaOf(String birth) => reduce22(int.parse(birth.split('-')[2]));
int pairArcana(int a, int b) => reduce22(a + b);

