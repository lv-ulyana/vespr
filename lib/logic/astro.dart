int signIndex(String birth) {
  final p = birth.split('-').map(int.parse).toList();
  final m = p[1], d = p[2];
  var idx = 0; // Козеріг — кінець грудня і початок січня
  for (var i = 1; i < signs.length; i++) {
    if (m > signs[i].m || (m == signs[i].m && d >= signs[i].d)) idx = i;
  }
  if (m == 12 && d >= 22) idx = 0;
  return idx;
}

