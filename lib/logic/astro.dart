class Astro {
  final int sign;
  final int? arc;
  const Astro(this.sign, this.arc);
  String get signName => signs[sign].name;
  String get el => signs[sign].el;
  String? get romanNum => arc == null ? null : roman[arc!];
  String? get arcanaName => arc == null ? null : arcana[arc!].name;
}

Astro? astroOf(String? birth, [int? signOnly]) {
  if (birth != null) return Astro(signIndex(birth), arcanaOf(birth));
  if (signOnly != null) return Astro(signOnly, null);
  return null;
}
